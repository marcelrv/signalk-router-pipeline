#!/usr/bin/env python3
"""Regenerate docs/CLI-REFERENCE.md from every tool's own --help output.

The argparse help strings in each tool are the source of truth; this just collects them in one place.
Usage: python3 scripts/gen_cli_reference.py [--output docs/CLI-REFERENCE.md]
"""
import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (script, role in the pipeline). Order follows the build flow.
TOOLS = [
    ("scripts/download_noaa.py", "Download NOAA ENC chart cells for a region."),
    ("enc_preprocessor.py", "Extract S-57 layers from raw .000 cells into GeoJSON."),
    ("clip_pilot_data.py", "Clip extracted GeoJSON to a bounding box (pilot / sub-region builds)."),
    ("derive_channel_axes.py", "Derive marked-channel axes from buoys/beacons and fairway polygons."),
    ("nautical_routing_pipeline.py", "Build the routing-graph SQLite from the GeoJSON layers."),
    ("add_pois_to_db.py", "Add points of interest to an existing routing DB."),
    ("review_region.py", "Graph cleanup: render tiles, have a reviewer (mock/claude/local) answer them, write ops."),
    ("apply_cleanup.py", "Apply (or replay) cleanup ops to a routing DB."),
    ("scripts/review_hazard_text.py", "Review chart text that implies time limits (list/propose/accept/reject)."),
    ("deploy_to_data_repo.py", "Publish a finished DB to the signalk-router-data repo."),
]


def help_of(script):
    env = dict(os.environ, COLUMNS="100")
    r = subprocess.run([sys.executable, os.path.join(ROOT, script), "--help"], cwd=ROOT, env=env,
                       capture_output=True, text=True, check=True)
    return r.stdout.rstrip()


def shell_header():
    lines = []
    with open(os.path.join(ROOT, "build_region.sh"), encoding="utf-8") as fh:
        for ln in fh.readlines()[1:]:
            if not ln.startswith("#"):
                break
            lines.append(ln[2:].rstrip() if ln.startswith("# ") else "")
    return "\n".join(lines).rstrip()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output", default=os.path.join(ROOT, "docs", "CLI-REFERENCE.md"))
    a = ap.parse_args()
    out = ["# Command-line reference", "",
           "Generated by `scripts/gen_cli_reference.py` from each tool's `--help`; do not edit by hand "
           "(fix the argparse help in the tool, then regenerate).", "",
           "Typical flow: `build_region.sh` runs download -> `enc_preprocessor.py` -> `nautical_routing_pipeline.py` "
           "end to end. The other tools are used individually for channel axes, POIs, graph cleanup and release.", "",
           "## build_region.sh", "", "End-to-end driver (header comment of the script):", "", "```text",
           shell_header(), "```", ""]
    for script, role in TOOLS:
        out += [f"## {script}", "", role, "", "```text", help_of(script), "```", ""]
    with open(a.output, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("wrote", a.output)


if __name__ == "__main__":
    main()
